'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, 'root/www/luci-static/resources/view/fail2ban/manager.js'), 'utf8');
new Function(source);
const helpers = source.slice(source.indexOf('function formatTime'), source.indexOf('return view.extend'));
const context = { E: () => {}, String, Date, Object };
vm.createContext(context);
vm.runInContext(helpers, context);
assert.equal(context.formatTime('Sun Sep  6 22:09:12 2026'), '2026-09-06 22:09:12');
assert.equal(context.formatTime('2026-09-06 22:09:12'), '2026-09-06 22:09:12');
assert.equal(context.formatTime(new Date(2026, 8, 6, 22, 9, 12)), '2026-09-06 22:09:12');
assert.equal(context.duration(-1), '\u6c38\u4e45');
assert.equal(context.duration(30), '30\u79d2');
assert.equal(context.duration(600), '10\u5206\u949f');
assert(!source.includes('toLocaleTimeString'));
assert(source.includes('Object.keys(names).sort()'));
assert(source.includes('Object.prototype.hasOwnProperty.call(names, group)'));
assert(source.includes('self.writable ?'));
console.log('Frontend syntax, timestamps, durations, dynamic filtering and permission guard passed.');
